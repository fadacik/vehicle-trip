-- =====================================================================
-- V1: Sema
-- Durumlar (status) VARCHAR + CHECK ile tutulur; JPA tarafinda
-- @Enumerated(EnumType.STRING) ile eslenir.
-- =====================================================================

-- ---------- Kullanicilar ----------
CREATE TABLE users (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    full_name         VARCHAR(150) NOT NULL,
    phone             VARCHAR(20)  NOT NULL,
    national_id       VARCHAR(11)  NOT NULL,
    profile_photo_url VARCHAR(500),
    status            VARCHAR(20)  NOT NULL DEFAULT 'PENDING',
    created_at        TIMESTAMPTZ  NOT NULL DEFAULT now(),
    verified_at       TIMESTAMPTZ,
    CONSTRAINT uq_users_phone UNIQUE (phone),
    CONSTRAINT ck_users_status CHECK (status IN ('PENDING', 'VERIFIED', 'SUSPENDED'))
);

-- ---------- OTP kodlari ----------
CREATE TABLE otp_codes (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id     BIGINT      NOT NULL REFERENCES users (id),
    code        VARCHAR(6)  NOT NULL,
    expires_at  TIMESTAMPTZ NOT NULL,
    used        BOOLEAN     NOT NULL DEFAULT FALSE,
    used_at     TIMESTAMPTZ,
    created_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT ck_otp_code_format CHECK (code ~ '^[0-9]{6}$')
);
CREATE INDEX idx_otp_user ON otp_codes (user_id, created_at DESC);

-- ---------- Sehir tarifeleri ----------
CREATE TABLE city_tariffs (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    city          VARCHAR(80)    NOT NULL,
    price_per_km  NUMERIC(10, 2) NOT NULL,
    currency      VARCHAR(3)     NOT NULL DEFAULT 'TRY',
    CONSTRAINT uq_city_tariffs_city UNIQUE (city),
    CONSTRAINT ck_city_tariffs_price CHECK (price_per_km > 0)
);

-- ---------- Araclar ----------
-- version: optimistic locking icin (@Version)
CREATE TABLE vehicles (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    plate              VARCHAR(20)      NOT NULL,
    brand              VARCHAR(60)      NOT NULL,
    model              VARCHAR(60)      NOT NULL,
    city               VARCHAR(80)      NOT NULL,
    latitude           DOUBLE PRECISION NOT NULL,
    longitude          DOUBLE PRECISION NOT NULL,
    total_range_km     NUMERIC(8, 2)    NOT NULL,
    remaining_range_km NUMERIC(8, 2)    NOT NULL,
    status             VARCHAR(20)      NOT NULL DEFAULT 'AVAILABLE',
    version            BIGINT           NOT NULL DEFAULT 0,
    CONSTRAINT uq_vehicles_plate UNIQUE (plate),
    CONSTRAINT ck_vehicles_status CHECK (status IN ('AVAILABLE', 'IN_USE', 'MAINTENANCE')),
    CONSTRAINT ck_vehicles_range CHECK (
        total_range_km > 0
        AND remaining_range_km >= 0
        AND remaining_range_km <= total_range_km
    )
);

-- ---------- Arac kullanim alanlari (merkez + yaricap) ----------
CREATE TABLE vehicle_zones (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    vehicle_id       BIGINT           NOT NULL REFERENCES vehicles (id),
    name             VARCHAR(100)     NOT NULL,
    center_latitude  DOUBLE PRECISION NOT NULL,
    center_longitude DOUBLE PRECISION NOT NULL,
    radius_km        NUMERIC(8, 2)    NOT NULL,
    CONSTRAINT ck_vehicle_zones_radius CHECK (radius_km > 0)
);
CREATE INDEX idx_vehicle_zones_vehicle ON vehicle_zones (vehicle_id);

-- ---------- Cuzdanlar ----------
CREATE TABLE wallets (
    id       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id  BIGINT         NOT NULL REFERENCES users (id),
    balance  NUMERIC(12, 2) NOT NULL DEFAULT 0,
    version  BIGINT         NOT NULL DEFAULT 0,
    CONSTRAINT uq_wallets_user UNIQUE (user_id),
    CONSTRAINT ck_wallets_balance CHECK (balance >= 0)
);

-- ---------- Seyahatler ----------
CREATE TABLE trips (
    id                      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id                 BIGINT           NOT NULL REFERENCES users (id),
    vehicle_id              BIGINT           NOT NULL REFERENCES vehicles (id),
    status                  VARCHAR(20)      NOT NULL DEFAULT 'CREATED',
    city                    VARCHAR(80)      NOT NULL,
    price_per_km            NUMERIC(10, 2)   NOT NULL,
    start_latitude          DOUBLE PRECISION NOT NULL,
    start_longitude         DOUBLE PRECISION NOT NULL,
    destination_latitude    DOUBLE PRECISION NOT NULL,
    destination_longitude   DOUBLE PRECISION NOT NULL,
    estimated_distance_km   NUMERIC(10, 2)   NOT NULL,
    estimated_duration_min  INTEGER          NOT NULL,
    estimated_fee           NUMERIC(12, 2)   NOT NULL,
    actual_distance_km      NUMERIC(10, 2),
    actual_duration_min     INTEGER,
    created_at              TIMESTAMPTZ      NOT NULL DEFAULT now(),
    started_at              TIMESTAMPTZ,
    completed_at            TIMESTAMPTZ,
    version                 BIGINT           NOT NULL DEFAULT 0,
    CONSTRAINT ck_trips_status CHECK (status IN ('CREATED', 'ACTIVE', 'COMPLETED', 'CANCELLED')),
    CONSTRAINT ck_trips_estimates CHECK (
        estimated_distance_km >= 0 AND estimated_duration_min >= 0 AND estimated_fee >= 0
    )
);
CREATE INDEX idx_trips_user ON trips (user_id);
CREATE INDEX idx_trips_vehicle ON trips (vehicle_id);

-- Ayni arac icin ayni anda yalnizca bir ACTIVE seyahat (eszamanlilik korumasi, DB seviyesinde)
CREATE UNIQUE INDEX uq_trips_one_active_per_vehicle ON trips (vehicle_id) WHERE status = 'ACTIVE';
-- Bir kullanici ayni anda yalnizca bir ACTIVE seyahat yapabilir
CREATE UNIQUE INDEX uq_trips_one_active_per_user ON trips (user_id) WHERE status = 'ACTIVE';

-- ---------- Seyahat konumlari ----------
CREATE TABLE trip_locations (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    trip_id      BIGINT           NOT NULL REFERENCES trips (id),
    latitude     DOUBLE PRECISION NOT NULL,
    longitude    DOUBLE PRECISION NOT NULL,
    recorded_at  TIMESTAMPTZ      NOT NULL,
    city         VARCHAR(80),
    speed_kmh    NUMERIC(6, 2),
    -- Ayni seyahat icin ayni zaman damgasiyla tekrar eden kayit engellenir
    CONSTRAINT uq_trip_locations_trip_time UNIQUE (trip_id, recorded_at),
    CONSTRAINT ck_trip_locations_speed CHECK (speed_kmh IS NULL OR speed_kmh >= 0),
    CONSTRAINT ck_trip_locations_lat CHECK (latitude BETWEEN -90 AND 90),
    CONSTRAINT ck_trip_locations_lng CHECK (longitude BETWEEN -180 AND 180)
);
CREATE INDEX idx_trip_locations_trip ON trip_locations (trip_id, recorded_at);

-- ---------- Seyahat ucretleri ----------
-- Ayni seyahat icin ayni kalemden yalnizca bir kayit (mukerrer tahsilat korumasi)
CREATE TABLE trip_fees (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    trip_id     BIGINT         NOT NULL REFERENCES trips (id),
    fee_type    VARCHAR(30)    NOT NULL DEFAULT 'DISTANCE',
    amount      NUMERIC(12, 2) NOT NULL,
    status      VARCHAR(20)    NOT NULL DEFAULT 'PENDING',
    created_at  TIMESTAMPTZ    NOT NULL DEFAULT now(),
    charged_at  TIMESTAMPTZ,
    CONSTRAINT uq_trip_fees_trip_type UNIQUE (trip_id, fee_type),
    CONSTRAINT ck_trip_fees_amount CHECK (amount >= 0),
    CONSTRAINT ck_trip_fees_status CHECK (status IN ('PENDING', 'CHARGED', 'FAILED'))
);

-- ---------- Cuzdan hareketleri (ayri defter) ----------
CREATE TABLE wallet_transactions (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    wallet_id      BIGINT         NOT NULL REFERENCES wallets (id),
    trip_id        BIGINT         REFERENCES trips (id),
    type           VARCHAR(20)    NOT NULL,
    amount         NUMERIC(12, 2) NOT NULL,
    balance_after  NUMERIC(12, 2) NOT NULL,
    description    VARCHAR(255),
    created_at     TIMESTAMPTZ    NOT NULL DEFAULT now(),
    CONSTRAINT ck_wallet_tx_type CHECK (type IN ('TOP_UP', 'TRIP_CHARGE', 'REFUND')),
    CONSTRAINT ck_wallet_tx_amount CHECK (amount > 0),
    CONSTRAINT ck_wallet_tx_balance_after CHECK (balance_after >= 0)
);
CREATE INDEX idx_wallet_tx_wallet ON wallet_transactions (wallet_id, created_at DESC);

-- Bir seyahat icin yalnizca bir TRIP_CHARGE hareketi olabilir
CREATE UNIQUE INDEX uq_wallet_tx_one_charge_per_trip
    ON wallet_transactions (trip_id) WHERE type = 'TRIP_CHARGE';

-- ---------- Ariza bildirimleri ----------
CREATE TABLE fault_reports (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    trip_id      BIGINT       NOT NULL REFERENCES trips (id),
    vehicle_id   BIGINT       NOT NULL REFERENCES vehicles (id),
    fault_type   VARCHAR(30)  NOT NULL,
    description  VARCHAR(500),
    reported_at  TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CONSTRAINT ck_fault_type CHECK (fault_type IN ('TIRE_BLOWOUT', 'BATTERY', 'DOOR', 'ENGINE', 'OTHER'))
);
CREATE INDEX idx_fault_reports_trip ON fault_reports (trip_id);

-- ---------- Seyahat uyarilari ----------
CREATE TABLE trip_warnings (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    trip_id       BIGINT       NOT NULL REFERENCES trips (id),
    warning_type  VARCHAR(30)  NOT NULL,
    message       VARCHAR(500) NOT NULL,
    created_at    TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CONSTRAINT ck_warning_type CHECK (warning_type IN ('SPEED_LIMIT', 'DURATION_EXCEEDED'))
);
CREATE INDEX idx_trip_warnings_trip ON trip_warnings (trip_id);
