CREATE TABLE trip_photos (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    trip_id     BIGINT       NOT NULL REFERENCES trips (id),
    phase       VARCHAR(10)  NOT NULL,
    photo_type  VARCHAR(20)  NOT NULL,
    url         VARCHAR(500) NOT NULL,
    uploaded_at TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CONSTRAINT ck_trip_photos_phase CHECK (phase IN ('START', 'END')),
    CONSTRAINT ck_trip_photos_photo_type CHECK (photo_type IN ('FRONT_SEAT', 'BACK_SEAT', 'EXTERIOR')),
    CONSTRAINT uq_trip_photos_trip_phase_type UNIQUE (trip_id, phase, photo_type)
);

CREATE INDEX idx_trip_photos_trip ON trip_photos (trip_id);

CREATE TABLE trip_damages (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    trip_id       BIGINT        NOT NULL REFERENCES trips (id),
    photo_type    VARCHAR(20)   NOT NULL,
    damage_kind   VARCHAR(20)   NOT NULL,
    description   VARCHAR(500),
    cost          NUMERIC(12,2) NOT NULL,
    detected_at   TIMESTAMPTZ   NOT NULL DEFAULT now(),
    CONSTRAINT ck_trip_damages_photo_type CHECK (photo_type IN ('FRONT_SEAT', 'BACK_SEAT', 'EXTERIOR')),
    CONSTRAINT ck_trip_damages_damage_kind CHECK (damage_kind IN ('DAMAGE', 'MISSING_ITEM')),
    CONSTRAINT ck_trip_damages_cost CHECK (cost >= 0),
    CONSTRAINT uq_trip_damages_trip_photo_type UNIQUE (trip_id, photo_type)
);

CREATE INDEX idx_trip_damages_trip ON trip_damages (trip_id);
