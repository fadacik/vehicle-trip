-- V3: Adim 17 / BLOK A — Araç kapisi islem kayitlari (bonus)
-- Durumlar VARCHAR + CHECK; JPA tarafinda @Enumerated(EnumType.STRING).
-- KISMI UNIQUE: bir seyahatte en cok bir basarili TRIP_START UNLOCK ve
-- bir basarili TRIP_COMPLETE LOCK kaydi (COMPENSATION kapsam disi).
-- =====================================================================

CREATE TABLE trip_door_actions (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    trip_id    BIGINT       NOT NULL REFERENCES trips (id),
    vehicle_id BIGINT       NOT NULL REFERENCES vehicles (id),
    action     VARCHAR(20)  NOT NULL,
    status     VARCHAR(20)  NOT NULL,
    reason     VARCHAR(30)  NOT NULL,
    message    VARCHAR(500),
    created_at TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CONSTRAINT ck_trip_door_actions_action CHECK (action IN ('UNLOCK', 'LOCK')),
    CONSTRAINT ck_trip_door_actions_status CHECK (status IN ('SUCCESS', 'FAILED')),
    CONSTRAINT ck_trip_door_actions_reason CHECK (reason IN ('TRIP_START', 'TRIP_COMPLETE', 'COMPENSATION'))
);

CREATE INDEX idx_trip_door_actions_trip_time ON trip_door_actions (trip_id, created_at);

-- Denetim izi degismezi: ayni seyahat + ayni action icin tek basarili
-- (SUCCESS) ana akis kaydi. FAILED ve COMPENSATION kayitlari bu kuralin
-- disindadir; tekrar denemeler ve telafiler bundan etkilenmez.
CREATE UNIQUE INDEX uq_trip_door_one_success_per_action
    ON trip_door_actions (trip_id, action)
    WHERE status = 'SUCCESS' AND reason IN ('TRIP_START', 'TRIP_COMPLETE');
